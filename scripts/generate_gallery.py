#!/usr/bin/env python3
"""Generate GALLERY.md from dialect YAML definitions."""
import re
import yaml
from pathlib import Path

# Use the same paths as the dialect system
DEFINITIONS_DIR = Path(__file__).parent.parent / "bioLOLPython" / "dialects" / "definitions"
OUTPUT = Path(__file__).parent.parent / "GALLERY.md"

COMMAND_ORDER = [
    "init", "end", "declare", "reverse", "gc_content",
    "print", "transcribe", "translate", "align", "mutate",
    "length", "complement", "find_orf", "motif",
]


def era_sort_key(dialect):
    """Extract first 4-digit year from era string for sorting."""
    m = re.search(r"\d{4}", dialect.get("era", "9999"))
    return int(m.group()) if m else 9999


def generate():
    # Load all YAML dialect files
    dialects = []
    for path in sorted(DEFINITIONS_DIR.glob("*.yaml")):
        with open(path, "r", encoding="utf-8") as f:
            dialects.append(yaml.safe_load(f))

    dialects.sort(key=era_sort_key)

    lines = [
        "<!-- AUTO-GENERATED by scripts/generate_gallery.py — do not edit by hand -->",
        "<!-- Want to add a dialect? See Readme.md#creating-a-new-dialect -->",
        "",
        "# Dialect Gallery",
        "",
        f"*{len(dialects)} dialects, sorted chronologically.*",
        "",
    ]

    for dialect in dialects:
        name = dialect["name"]
        era = dialect.get("era", "")
        desc = dialect.get("description", "")
        commands = dialect.get("commands", {})
        examples = dialect.get("examples", {})

        lines.append("---")
        lines.append("")
        lines.append(f"## {name} (`{era}`)")
        lines.append("")
        lines.append(desc)
        lines.append("")

        # Command table
        lines.append("### Commands")
        lines.append("")
        lines.append("| Command | Syntax |")
        lines.append("|---|---|")
        for cmd in COMMAND_ORDER:
            if cmd in commands:
                pattern = commands[cmd].get("pattern", "")
                lines.append(f"| {cmd} | `{pattern}` |")
        lines.append("")

        # First example
        if examples:
            first_name = next(iter(examples))
            first_code = examples[first_name].rstrip()
            lines.append(f"### Example: {first_name}")
            lines.append("")
            lines.append("```")
            lines.append(first_code)
            lines.append("```")
            lines.append("")

    output = "\n".join(lines)
    OUTPUT.write_text(output, encoding="utf-8")
    print(f"Generated {OUTPUT} with {len(dialects)} dialect(s).")


if __name__ == "__main__":
    generate()
